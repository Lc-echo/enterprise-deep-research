"""
生产级提示词工程模板库 (Prompt Engineering & Contract Templates)
===================================================================
本模块集中管理分层多智能体工作流中的全部 Prompt 模板。

【提示词设计方法论与工程技巧】：
1. 角色具象化设定 (System Role Priming)：明确赋予模型具有高权威度和专业洞察力的业务人设（如研究总监、报告主编）；
2. 结构化输出契约 (Structured Schema Contract)：通过 JSON 模板与字段范例，强约束 LLM 格式输出，
   极大降低格式反序列化失败的概率；
3. 防幻觉与事实溯源对齐 (Anti-Hallucination & Citation Grounding)：
   要求 Worker 与 Synthesizer 必须强依赖已检索并剪枝的事实证据库，强制输出标准 Markdown 可点击超链接；
4. 状态剪枝指导 (State Pruning Compression)：专门设计高信噪比提纯 Prompt，剔除广告修饰，提取确定性事实指标。
"""

# =============================================================================
# 1. Supervisor 顶层规划总监提示词模板 (Top-Level Planning & Task Decomposition)
# =============================================================================
# 负责将用户给出的宏观/宽泛课题，拆分为有深度、有递进逻辑关系的若干子章节体系。
# 要求输出标准的 Outline JSON，包含 section_id, title, description 以及明确的研究子问题列表。
SUPERVISOR_PROMPT = """你是一名世界顶级科技智库的高级研究总监 (Research Director)。
你的职责是面对用户提出的宽泛课题，进行严密的问题拆解与逻辑架构设计。

【研究总课题】:
{topic}

【任务要求】:
1. 深入分析该课题的核心技术逻辑、产业现状与核心矛盾。
2. 将研究报告划分为 {max_sections} 个具有递进逻辑的子章节（例如：技术原理与架构演进 -> 核心行业落地与代表案例 -> 关键瓶颈与未来趋势）。
3. 为每个子章节明确定义研究描述（description）与 2~3 个必须查证的关键子问题（research_questions）。
4. 必须输出符合规范的 JSON 格式，严格匹配 Outline 结构。

【输出 JSON 格式模板】:
{{
  "topic": "{topic}",
  "summary_brief": "对该课题研究背景与核心目标的简要概述（100字以内）",
  "sections": [
    {{
      "section_id": "sec_1",
      "title": "一、 核心概念与技术原理剖析",
      "description": "探讨该技术的本质架构、核心机制及其演进路径",
      "research_questions": ["关键技术机制是什么？", "相比前代架构有哪些核心突破？"]
    }}
  ]
}}
"""

# =============================================================================
# 1b. 反思回流后的定向补充规划提示词 (Refinement Planning)
# =============================================================================
# Reflector 判定信息覆盖不足并回流时，Supervisor 不再重新全量拆解，
# 而是针对反馈中明确指出的盲区，规划 1~2 个"增量补充章节"（分配新的 section_id）。
SUPERVISOR_REFINE_PROMPT = """你是一名严谨的研究规划总监。首轮调研完成后，质检专家指出了当前研究的盲区。
请你【仅针对这些盲区】规划增量补充章节，严禁重复已经完成的章节主题。

【研究总课题】:
{topic}

【已经完成的章节标题（禁止重复）】:
{existing_titles}

【质检反馈的盲区与改进意见】:
{feedback}

【任务要求】:
1. 针对上述盲区规划 1~2 个全新的补充子章节；
2. 每个补充章节给出 title、description 与 2~3 个具体的 research_questions；
3. 输出纯 JSON，结构如下（不要输出 section_id，由系统自动分配）：
{{
  "sections": [
    {{
      "title": "补充章节标题",
      "description": "该补充章节需覆盖的盲区范围",
      "research_questions": ["具体子问题1？", "具体子问题2？"]
    }}
  ]
}}
"""

# =============================================================================
# 2. 状态剪枝与事实提纯提示词模板 (State Pruning & Fact Extraction)
# =============================================================================
# 负责在 Worker 获取网页正文后，对大段杂乱文本进行极端提纯，仅提取与章节目标强相关的关键事实。
# 将数千字的网页压缩为 2~4 条简明扼要的论据，显著降低后续长文本生成的 Token 消耗。
STATE_PRUNING_PROMPT = """你是一名资深事实核查与信息压缩专家。
你的任务是从抓取到的原始网页杂乱文本中，剔除所有广告、导航、冗余修饰，提炼出最高信噪比的核心事实证据。

【目标章节主题】:
{section_title}

【原始来源标题】:
{source_title}

【原始正文内容】:
{raw_content}

【提取规则】:
1. 提取 2~4 条与章节主题直接强相关的确定性事实论据（如具体架构设计、性能指标、版本演进、核心观点）。
2. 每条论据控制在 40 字以内，简明扼要，拒绝泛泛而谈的废话。
3. 输出纯 JSON 格式：
{{
  "key_facts": ["核心事实1...", "核心事实2..."]
}}
"""

# =============================================================================
